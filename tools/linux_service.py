"""Standard-library helpers for the Linux shell scripts; no elevated execution."""

from __future__ import annotations

import argparse
from contextlib import closing
from datetime import datetime, timezone
import ipaddress
import json
import os
from pathlib import Path, PurePosixPath
import re
import sqlite3
import sys
import tempfile
import time
from urllib.error import URLError
from urllib.request import ProxyHandler, build_opener
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
CONFIG = Path('/etc/b1-training-app.json')
DATA_DIR = Path('/var/lib/b1-training-app')
DATABASE = DATA_DIR / 'practice.sqlite3'
SERVICE = 'b1-training-app.service'
TABLES = {
    'users': {'id', 'name', 'created_at'},
    'browser_sessions': {'token', 'user_id', 'created_at'},
    'practice': {'id', 'user_id', 'unit_id', 'mode', 'question_ids', 'created_at', 'completed_at'},
    'answers': {'practice_id', 'question_id', 'choice', 'correct', 'answered_at'},
    'question_state': {'user_id', 'question_id', 'correct', 'updated_at'},
}


def safe_service_path(value):
    """Restrict systemd paths so no unit, specifier, or environment escaping is needed."""
    path = str(value)
    if not re.fullmatch(r'/[A-Za-z0-9_./@+\-]+', path) or '..' in PurePosixPath(path).parts:
        raise ValueError('The checkout and Python paths must use only ASCII letters, digits, / . _ @ + - (no spaces).')
    return path


def load_config():
    if not CONFIG.is_file():
        raise ValueError('Not installed. Run bash scripts/install-linux.sh first.')
    config = json.loads(CONFIG.read_text(encoding='utf-8'))
    if config.get('format') != 1:
        raise ValueError('Unsupported installation configuration format.')
    if config['repo'] != str(ROOT) or config['uid'] != os.getuid():
        raise ValueError('This service belongs to a different checkout or user. Use the original checkout and account.')
    if not Path(config['python']).is_file():
        raise ValueError('The installed Python interpreter is missing. Re-run install-linux.sh with Python 3.10+ available.')
    return config


def render_unit(config):
    repo = safe_service_path(config['repo'])
    python = safe_service_path(config['python'])
    return f'''# Generated by scripts/install-linux.sh. Re-run the installer to change settings.
[Unit]
Description=Schritt German B1 training app
Wants=network-online.target
After=network-online.target
StartLimitIntervalSec=0

[Service]
Type=exec
User={config['uid']}
Group={config['gid']}
WorkingDirectory={repo}
ExecStart={python} -B -u {repo}/app.py --host {config['host']} --port {config['port']} --database {DATABASE.as_posix()}
Restart=on-failure
RestartSec=3
KillSignal=SIGINT
TimeoutStopSec=20
UMask=0077
StateDirectory=b1-training-app
StateDirectoryMode=0700
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=strict
ProtectHome=read-only

[Install]
WantedBy=multi-user.target
'''


def prepare(host, port, output, import_db):
    uid, gid = os.getuid(), os.getgid()
    if uid == 0:
        raise ValueError('Run as your normal login user, not root.')
    old = load_config() if CONFIG.exists() else {}
    host = host or old.get('host', '0.0.0.0')
    if not isinstance(ipaddress.ip_address(host), ipaddress.IPv4Address):
        raise ValueError('Use an IPv4 bind address; the app currently serves IPv4.')
    port = int(port or old.get('port', 8188))
    if not 1024 <= port <= 65535:
        raise ValueError('Choose an unprivileged port from 1024 through 65535.')
    if DATA_DIR.exists() and DATA_DIR.stat().st_uid != uid:
        raise ValueError(f'{DATA_DIR} belongs to another account; refusing to change ownership.')
    if import_db:
        validate_database(Path(import_db))
        if DATABASE.exists():
            raise ValueError('A service database already exists. Use service-linux.sh restore explicitly instead.')
    elif not DATABASE.exists() and (ROOT / 'instance' / 'practice.sqlite3').exists():
        raise ValueError('An existing manual-run database was found. Re-run with --import-db instance/practice.sqlite3 to preserve it.')
    config = {'format': 1, 'repo': safe_service_path(ROOT),
              'python': safe_service_path(sys.executable), 'uid': uid, 'gid': gid,
              'host': host, 'port': port}
    output = Path(output)
    (output / SERVICE).write_text(render_unit(config), encoding='utf-8', newline='\n')
    (output / 'config.json').write_text(json.dumps(config, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(f'Checkout: {ROOT}\nService user UID: {uid}\nListen: {host}:{port}\nProgress: {DATABASE}')


def read_database(path):
    path = Path(path).resolve()
    if not path.is_file():
        raise ValueError(f'Database file does not exist: {path}')
    return sqlite3.connect(path.as_uri() + '?mode=ro', uri=True, timeout=15)


def validate_database(path):
    with closing(read_database(path)) as db:
        if db.execute('PRAGMA quick_check').fetchall() != [('ok',)]:
            raise ValueError(f'SQLite integrity check failed: {path}')
        for table, expected in TABLES.items():
            columns = {row[1] for row in db.execute(f'PRAGMA table_info({table})')}
            if not expected <= columns:
                raise ValueError(f'Not a compatible app database: missing columns in {table}.')
        if db.execute('PRAGMA foreign_key_check').fetchone():
            raise ValueError(f'Database has broken references: {path}')


def copy_database(source, target):
    """SQLite backup API includes committed WAL data, unlike a live file copy."""
    if Path(source).resolve() == Path(target).resolve():
        raise ValueError('Source and destination databases must be different files.')
    validate_database(source)
    deadline = time.monotonic() + 60

    def progress(status, remaining, total):
        if time.monotonic() > deadline:
            raise TimeoutError('Database backup timed out; try again during a quieter period.')

    with closing(read_database(source)) as src, closing(sqlite3.connect(target, timeout=15)) as dest:
        src.backup(dest, pages=256, progress=progress, sleep=0.05)
    validate_database(target)


def backup(if_exists=False):
    if not DATABASE.exists():
        if if_exists:
            print('No service database yet; it will be created at first startup.')
            return None
        raise ValueError('There is no service database to back up.')
    folder = DATA_DIR / 'backups'
    folder.mkdir(mode=0o700, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    target = folder / f'practice-{stamp}-{uuid4().hex[:8]}.sqlite3'
    # The incomplete snapshot is never presented as a finished backup.
    fd, temporary = tempfile.mkstemp(prefix='.backup-', suffix='.partial', dir=folder)
    os.close(fd)
    try:
        copy_database(DATABASE, temporary)
        os.replace(temporary, target)
    finally:
        Path(temporary).unlink(missing_ok=True)
    print(f'Backup: {target}')
    return target


def import_database(source):
    if DATABASE.exists():
        raise ValueError('Refusing to overwrite existing service progress during installation.')
    # Create exclusively; cleanup only the new file if import fails.
    fd = os.open(DATABASE, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    os.close(fd)
    try:
        copy_database(source, DATABASE)
    except Exception:
        DATABASE.unlink(missing_ok=True)
        raise
    print(f'Imported progress from {Path(source).resolve()}')


def health():
    config = load_config()
    host = '127.0.0.1' if config['host'] == '0.0.0.0' else config['host']
    url = f'http://{host}:{config["port"]}/api/users'
    opener = build_opener(ProxyHandler({}))  # A local check must not go through a proxy.
    deadline = time.monotonic() + 30
    last_error = ''
    while time.monotonic() < deadline:
        try:
            with opener.open(url, timeout=1) as response:
                data = json.load(response)
            if not isinstance(data, dict) or not isinstance(data.get('users'), list) or not isinstance(data.get('prepared'), int):
                raise ValueError('Unexpected app response.')
            print(f'App responds at http://{host}:{config["port"]} ({data["prepared"]} units).')
            if config['host'] == '0.0.0.0':
                print(f'Other WLAN devices: http://YOUR-LINUX-IP:{config["port"]}')
            return
        except (URLError, OSError, ValueError) as exc:
            last_error = str(exc)
            time.sleep(0.25)
    raise ValueError(f'The app did not become ready at {url}: {last_error}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    setup = commands.add_parser('prepare')
    setup.add_argument('--host', default='')
    setup.add_argument('--port', default='')
    setup.add_argument('--output', type=Path, required=True)
    setup.add_argument('--import-db', default='')
    commands.add_parser('interpreter')
    commands.add_parser('health')
    snapshot = commands.add_parser('backup')
    snapshot.add_argument('--if-exists', action='store_true')
    for name in ('import-db', 'restore', 'validate-db'):
        commands.add_parser(name).add_argument('source', type=Path)
    args = parser.parse_args()
    try:
        if args.command == 'prepare':
            prepare(args.host, args.port, args.output, args.import_db)
        elif args.command == 'import-db':
            # First installation has no configuration yet.
            import_database(args.source)
        elif args.command == 'validate-db':
            validate_database(args.source)
        else:
            config = load_config()
            if args.command == 'interpreter':
                print(config['python'])
            elif args.command == 'health':
                health()
            elif args.command == 'backup':
                backup(args.if_exists)
            elif args.command == 'restore':
                copy_database(args.source, DATABASE)
                print(f'Restored progress from {args.source.resolve()}')
    except (OSError, ValueError, KeyError, sqlite3.Error) as exc:
        parser.exit(1, f'Error: {exc}\n')


if __name__ == '__main__':
    main()
